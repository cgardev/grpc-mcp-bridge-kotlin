package io.github.cgardev.library.protobuf.jsonschema.internal

import io.github.cgardev.library.protobuf.jsonschema.EnumPolicy
import io.github.cgardev.library.protobuf.jsonschema.Options
import io.github.cgardev.library.protobuf.jsonschema.RootStyle
import com.fasterxml.jackson.databind.JsonNode
import com.fasterxml.jackson.databind.node.ArrayNode
import com.fasterxml.jackson.databind.node.JsonNodeFactory
import com.fasterxml.jackson.databind.node.ObjectNode
import com.google.protobuf.Descriptors
import com.google.protobuf.Descriptors.FieldDescriptor

internal class SchemaBuilder(private val options: Options) {

    private val nodes: JsonNodeFactory = JsonNodeFactory.instance
    private val defs: LinkedHashMap<String, ObjectNode> = linkedMapOf()
    private val inProgress: MutableSet<String> = linkedSetOf()

    fun build(root: Descriptors.Descriptor): ObjectNode {
        val document = nodes.objectNode()
        if (options.emitDollarSchema) {
            document.put("\$schema", "https://json-schema.org/draft/2020-12/schema")
        }
        val wktSchema = WellKnownTypes.schemaFor(root.fullName)
        if (wktSchema != null) {
            copyInto(document, wktSchema)
            return document
        }
        buildMessageSchema(root)
        when (options.rootStyle) {
            RootStyle.REF_TO_DEFS -> document.put("\$ref", "#/\$defs/${root.fullName}")
            RootStyle.INLINE -> {
                val inlined = defs.remove(root.fullName) ?: nodes.objectNode()
                copyInto(document, inlined)
            }
        }
        if (defs.isNotEmpty()) {
            val defsNode = nodes.objectNode()
            defs.forEach { (name, schema) -> defsNode.set<JsonNode>(name, schema) }
            document.set<JsonNode>("\$defs", defsNode)
        }
        return document
    }

    private fun copyInto(target: ObjectNode, source: ObjectNode) {
        val it = source.properties().iterator()
        while (it.hasNext()) {
            val entry = it.next()
            target.set<JsonNode>(entry.key, entry.value)
        }
    }

    private fun messageRef(descriptor: Descriptors.Descriptor): JsonNode {
        val fullName = descriptor.fullName
        WellKnownTypes.schemaFor(fullName)?.let { return it }
        if (fullName in defs || fullName in inProgress) {
            return refNode(fullName)
        }
        buildMessageSchema(descriptor)
        return refNode(fullName)
    }

    private fun buildMessageSchema(descriptor: Descriptors.Descriptor) {
        val fullName = descriptor.fullName
        inProgress.add(fullName)
        val schema = nodes.objectNode()
        schema.put("type", "object")
        val properties = nodes.objectNode()
        for (field in descriptor.fields) {
            properties.set<JsonNode>(FieldNames.of(field, options.fieldNamePolicy), schemaForField(field))
        }
        schema.set<JsonNode>("properties", properties)
        schema.put("additionalProperties", options.additionalProperties)

        val realOneofs = descriptor.realOneofs
        val exclusions = nodes.arrayNode()
        for (oneof in realOneofs) {
            addOneofExclusivity(oneof, exclusions)
        }
        if (exclusions.size() > 0) {
            schema.set<JsonNode>("allOf", exclusions)
        }

        defs[fullName] = schema
        inProgress.remove(fullName)
    }

    private val Descriptors.Descriptor.realOneofs: List<Descriptors.OneofDescriptor>
        get() = oneofs.filterNot { it.isSyntheticOptional() }

    /**
     * A oneof is synthetic when it was generated by protoc to back a `proto3 optional` field.
     * Such oneofs always contain a single field whose descriptor has `proto3_optional = true`.
     */
    private fun Descriptors.OneofDescriptor.isSyntheticOptional(): Boolean {
        if (fieldCount != 1) return false
        val only = getField(0)
        return only.toProto().proto3Optional
    }

    private fun addOneofExclusivity(oneof: Descriptors.OneofDescriptor, target: ArrayNode) {
        val variants = oneof.fields.map { FieldNames.of(it, options.fieldNamePolicy) }
        if (variants.size < 2) return
        for (i in variants.indices) {
            for (j in i + 1 until variants.size) {
                val not = nodes.objectNode()
                val required = nodes.arrayNode()
                required.add(variants[i])
                required.add(variants[j])
                val inner = nodes.objectNode()
                inner.set<JsonNode>("required", required)
                not.set<JsonNode>("not", inner)
                target.add(not)
            }
        }
    }

    private fun schemaForField(field: FieldDescriptor): JsonNode {
        if (field.isMapField) return mapSchema(field)
        val elementSchema = elementSchemaFor(field)
        if (field.isRepeated) {
            val array = nodes.objectNode()
            array.put("type", "array")
            array.set<JsonNode>("items", elementSchema)
            return array
        }
        return elementSchema
    }

    private fun mapSchema(field: FieldDescriptor): JsonNode {
        val entryDescriptor = field.messageType
        val valueField = entryDescriptor.findFieldByNumber(2)
            ?: error("Map entry message ${entryDescriptor.fullName} missing value field")
        val mapNode = nodes.objectNode()
        mapNode.put("type", "object")
        mapNode.set<JsonNode>("additionalProperties", elementSchemaFor(valueField))
        return mapNode
    }

    private fun elementSchemaFor(field: FieldDescriptor): JsonNode = when (field.javaType) {
        FieldDescriptor.JavaType.INT -> int32Schema(field)
        FieldDescriptor.JavaType.LONG -> int64Schema(field)
        FieldDescriptor.JavaType.FLOAT, FieldDescriptor.JavaType.DOUBLE -> floatLikeSchema()
        FieldDescriptor.JavaType.BOOLEAN -> nodes.objectNode().apply { put("type", "boolean") }
        FieldDescriptor.JavaType.STRING -> nodes.objectNode().apply { put("type", "string") }
        FieldDescriptor.JavaType.BYTE_STRING -> nodes.objectNode().apply {
            put("type", "string")
            put("contentEncoding", "base64")
        }
        FieldDescriptor.JavaType.ENUM -> enumSchema(field.enumType)
        FieldDescriptor.JavaType.MESSAGE -> messageRef(field.messageType)
    }

    private fun int32Schema(field: FieldDescriptor): ObjectNode {
        val unsigned = field.type == FieldDescriptor.Type.UINT32 || field.type == FieldDescriptor.Type.FIXED32
        return nodes.objectNode().apply {
            put("type", "integer")
            if (unsigned) {
                put("minimum", 0L)
                put("maximum", 4_294_967_295L)
            } else {
                put("minimum", Int.MIN_VALUE.toLong())
                put("maximum", Int.MAX_VALUE.toLong())
            }
        }
    }

    private fun int64Schema(field: FieldDescriptor): ObjectNode {
        val unsigned = field.type == FieldDescriptor.Type.UINT64 || field.type == FieldDescriptor.Type.FIXED64
        return nodes.objectNode().apply {
            val types = nodes.arrayNode()
            types.add("string")
            types.add("integer")
            set<JsonNode>("type", types)
            put("pattern", if (unsigned) "^\\d+$" else "^-?\\d+$")
        }
    }

    private fun floatLikeSchema(): ObjectNode = nodes.objectNode().apply {
        val oneOf = nodes.arrayNode()
        oneOf.add(nodes.objectNode().apply { put("type", "number") })
        oneOf.add(
            nodes.objectNode().apply {
                put("type", "string")
                val enum = nodes.arrayNode()
                enum.add("NaN")
                enum.add("Infinity")
                enum.add("-Infinity")
                set<JsonNode>("enum", enum)
            },
        )
        set<JsonNode>("oneOf", oneOf)
    }

    private fun enumSchema(enumDescriptor: Descriptors.EnumDescriptor): ObjectNode {
        val description = enumDescriptor.values.joinToString(", ") { "${it.name}=${it.number}" }
        val minTag = enumDescriptor.values.minOf { it.number }
        val maxTag = enumDescriptor.values.maxOf { it.number }
        return when (options.enumPolicy) {
            EnumPolicy.NAME_ONLY -> enumNameOnlySchema(enumDescriptor, description)
            EnumPolicy.NAME_OR_INTEGER -> enumNameOrIntegerSchema(enumDescriptor, description, minTag, maxTag)
            EnumPolicy.INTEGER_ONLY -> enumIntegerOnlySchema(description, minTag, maxTag)
        }
    }

    private fun enumNameOnlySchema(
        enumDescriptor: Descriptors.EnumDescriptor,
        description: String,
    ): ObjectNode = nodes.objectNode().apply {
        put("type", "string")
        set<JsonNode>("enum", enumNameArray(enumDescriptor))
        put("description", description)
    }

    private fun enumNameOrIntegerSchema(
        enumDescriptor: Descriptors.EnumDescriptor,
        description: String,
        minTag: Int,
        maxTag: Int,
    ): ObjectNode = nodes.objectNode().apply {
        val oneOf = nodes.arrayNode()
        oneOf.add(
            nodes.objectNode().apply {
                put("type", "string")
                set<JsonNode>("enum", enumNameArray(enumDescriptor))
            },
        )
        oneOf.add(
            nodes.objectNode().apply {
                put("type", "integer")
                put("minimum", minTag)
                put("maximum", maxTag)
            },
        )
        set<JsonNode>("oneOf", oneOf)
        put("description", description)
    }

    private fun enumIntegerOnlySchema(
        description: String,
        minTag: Int,
        maxTag: Int,
    ): ObjectNode = nodes.objectNode().apply {
        put("type", "integer")
        put("minimum", minTag)
        put("maximum", maxTag)
        put("description", description)
    }

    private fun enumNameArray(enumDescriptor: Descriptors.EnumDescriptor): ArrayNode {
        val enumValues = nodes.arrayNode()
        for (value in enumDescriptor.values) {
            enumValues.add(value.name)
        }
        return enumValues
    }

    private fun refNode(fullName: String): ObjectNode {
        val ref = nodes.objectNode()
        ref.put("\$ref", "#/\$defs/$fullName")
        return ref
    }
}
